package com.mgmi.platform.view.ViewGroup.widget;

import android.content.Context;
import android.util.AttributeSet;
import android.widget.FrameLayout;
import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

public class CreativeWidgetShadow extends FrameLayout {
    public CreativeWidgetShadow(@NonNull Context context) {
        super(context);
    }

    public CreativeWidgetShadow(@NonNull Context context, @Nullable AttributeSet attributeSet) {
        super(context, attributeSet);
    }

    public CreativeWidgetShadow(@NonNull Context context, @Nullable AttributeSet attributeSet, int i) {
        super(context, attributeSet, i);
    }
}
