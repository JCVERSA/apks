package defpackage;

public class kc8 {
    public final int a;
    public final int b;
    public final int c;
    public final int d;
    public final int e;
    public final hx8 f;
    public final rlb g;

    public kc8(hx8 hx8Var) {
        this.f = hx8Var;
        this.e = hx8Var.d();
        int iE = hx8Var.e();
        this.d = iE;
        this.a = iE << 1;
        int i = iE >> 2;
        this.b = i;
        this.c = (i * 2) - 1;
        this.g = hx8Var.g();
    }
}
